test('skip runs on open; day change clears worker; login does not send', () => {
  const page = read('pages/SalonProfile.tsx')
  const openStart = page.indexOf('function openPicker')
  const openEnd = page.indexOf('function closePicker')
  const open = page.slice(openStart, openEnd)
  expect(open).toMatch(/guestHoursSkip/)
  expect(open).not.toMatch(/createBooking/)

  const toggleStart = page.indexOf('function toggle')
  const toggleEnd = page.indexOf('function applyDay')
  expect(page.slice(toggleStart, toggleEnd)).not.toMatch(/guestHoursSkip/)

  const applyStart = page.indexOf('function applyDay')
  const applyEnd = page.indexOf('function openPicker')
  const apply = page.slice(applyStart, applyEnd)
  expect(apply).toMatch(/guestDayChange/)
  expect(apply).toMatch(/setWorkerChoice\(next\.workerId\)/)
  expect(apply).toMatch(/setPreferredTime\(next\.time\)/)
  expect(apply).not.toMatch(/guestHoursSkip/)

  expect(page).toMatch(/meData\?\.me == null[\s\S]*salon\.loginToRequest[\s\S]*AuthShell/)
  expect(page).toMatch(/onAuthenticated=\{\(\) => setNeedLogin\(false\)\}/)
  const sendStart = page.indexOf('async function send')
  const unauthAt = page.indexOf("code === 'UNAUTHENTICATED'", sendStart)
  const emailAt = page.indexOf("code === 'EMAIL_UNVERIFIED'", unauthAt)
  const unauth = page.slice(unauthAt, emailAt)
  expect(unauth).toMatch(/setNeedLogin\(true\)/)
  expect(unauth).not.toMatch(/setSelected|setPreferredDate|setWorkerChoice|setMode\('idle'\)/)
  expect(page).toMatch(/SAME_DAY_SERVICE/)
  expect(page).toMatch(/function onVerified/)
  expect(page.slice(page.indexOf('function onVerified'), page.indexOf('const catalog'))).toMatch(/canSendPicker[\s\S]*send\(input\)/)
  const sent = page.slice(page.indexOf('await createBooking'), page.indexOf('} catch'))
  expect(sent).toMatch(/setSent\(true\)/)
  expect(sent).not.toMatch(/setMode\('idle'\)/)
})

