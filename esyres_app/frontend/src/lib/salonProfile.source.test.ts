// @ts-nocheck — Node fs is not in the PWA tsconfig; Vitest runs this file.
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, test } from 'vitest'

const src = join(dirname(fileURLToPath(import.meta.url)), '..')

function read(rel: string): string {
  return readFileSync(join(src, rel), 'utf8')
}

test('salonHours does not import owner.ts', () => {
  expect(read('lib/salonHours.ts')).not.toMatch(/from '\.\/owner'/)
})

test('salon profile stack is address, empty aside, read-only hours, then the send pill, then services', () => {
  const page = read('pages/SalonProfile.tsx')
  const catalogStart = page.indexOf('  const catalog =')
  const viewStart = page.lastIndexOf('\n  return (')
  const catalog = page.slice(catalogStart, viewStart)
  const view = page.slice(viewStart)
  const beforeDialog = view.slice(0, view.indexOf('<dialog'))

  const nameAt = view.indexOf('{salon.name}')
  const addressAt = view.indexOf('{addressLine}')
  const splitAt = view.indexOf('SALON_BOOKING_SPLIT_CLASS')
  const asideAt = view.indexOf('SALON_BOOKING_ASIDE_CLASS')
  const catalogUseAt = view.indexOf('SALON_BOOKING_MAIN_CLASS}>{catalog}')

  expect(nameAt).toBeGreaterThan(-1)
  expect(addressAt).toBeGreaterThan(nameAt)
  expect(splitAt).toBeGreaterThan(addressAt)
  expect(asideAt).toBeGreaterThan(splitAt)
  expect(catalogUseAt).toBeGreaterThan(asideAt)
  expect(beforeDialog).not.toMatch(/salon\.success/)

  expect(view).toMatch(/showBookingColumn \?/)
  expect(page).toMatch(/const showBookingColumn = hasServices/)
  expect(page).not.toMatch(/const showBookingColumn = hasServices && !sent/)
  expect(view).toMatch(/aria-hidden="true"/)

  const hoursAt = catalog.indexOf("t('salon.hours')")
  const hoursMapAt = catalog.indexOf('salon.hours.map')
  const listEnd = catalog.indexOf('</ul>')
  const servicesAt = catalog.indexOf("t('salon.services')")
  const hoursMap = catalog.slice(hoursMapAt, listEnd)
  const afterList = catalog.slice(listEnd, servicesAt)

  expect(hoursAt).toBeGreaterThan(-1)
  expect(hoursMapAt).toBeGreaterThan(hoursAt)
  expect(servicesAt).toBeGreaterThan(listEnd)
  expect(catalog).not.toMatch(/salon\.sendHint/)
  expect(catalog).toMatch(/picking=\{false\}/)
  expect(hoursMap).not.toMatch(/<button/)
  expect(hoursMap).not.toMatch(/SALON_SEND_CLASS/)
  expect(hoursMap).not.toMatch(/onHoursTap|showDaySendPill|hoursRowTappable|hoursRowSelected/)
  expect(afterList).toMatch(/hasServices \?/)
  expect(afterList).toMatch(/SALON_SEND_CLASS/)
  expect(afterList).toMatch(/openPicker/)
  expect(afterList).not.toMatch(/createBooking/)
  expect(catalog).not.toMatch(/assistant\.ask|SALON_CHAT_CARD_CLASS/)

  expect(page).toMatch(/SalonServiceGroups/)
  expect(page).toMatch(/svc-cat-\$\{group\.id\}/)
  expect(page).toMatch(/hidden w-40 shrink-0 md:block/)
  expect(page).toMatch(/visible\.length >= 2/)
  expect(page).not.toMatch(/category\.\$\{/)
})

