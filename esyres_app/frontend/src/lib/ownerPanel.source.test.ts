test('Request Detail has form, read, and bounce; no WorkerPanel', () => {
  const detail = read('pages/OwnerRequestDetail.tsx')
  const cardClass = 'rounded-3xl bg-canvas p-4 md:p-6'
  const readyAt = detail.indexOf('<OwnerShell')
  expect(readyAt).toBeGreaterThan(-1)
  expect(detail.slice(0, readyAt)).not.toMatch(new RegExp(cardClass))
  expect(detail).not.toMatch(/max-w-xl/)
  expect(detail).not.toMatch(/shadow-/)
  expect(detail).not.toMatch(/md:grid/)
  expect(detail).not.toMatch(/GUEST_COLUMN_CLASS/)
  expect(detail.indexOf("t('owner.back')")).toBeLessThan(detail.indexOf(cardClass))
  expect(detail).toMatch(/search\.get\('from'\) === 'zapisi'/)
  expect(detail).toMatch(/ownerZapisiPath/)
  expect(detail).toMatch(/to=\{leavePath\}/)
  expect(detail.split(cardClass).length - 1).toBe(1)
  expect(detail).not.toMatch(/WorkerPanel/)
  expect(detail).not.toMatch(/formatOwnerDayHeading/)
  expect(detail).toMatch(/ownerDetailMode/)
  expect(detail).toMatch(/proposedStartsAt/)
  expect(detail).toMatch(/OCCUPYING_BOOKINGS_QUERY/)
  expect(detail).not.toMatch(/OCCUPYING_BOOKINGS_RANGE_QUERY/)
  expect(detail).toMatch(/PROPOSE_TIME_MUTATION/)
  expect(detail).toMatch(/ACCEPT_PREFERRED_TIME_MUTATION/)
  expect(detail).toMatch(/DECLINE_BOOKING_MUTATION/)
  expect(detail).toMatch(/MARK_NO_SHOW_MUTATION/)
  expect(detail).toMatch(/priorConfirmedBookings/)
  expect(detail).toMatch(/owner\.priorBookings/)
  expect(detail).toMatch(/owner\.noShow/)
  expect(detail).toMatch(/owner\.propose/)
  expect(detail).toMatch(/NOT_REQUESTED/)

  const card = detail.slice(detail.indexOf(cardClass))
  const bounceAt = card.indexOf("ownerDetailMode(booking.status) === 'bounce'")
  const readAt = card.indexOf("ownerDetailMode(booking.status) === 'read'")
  const formAt = card.indexOf("ownerDetailMode(booking.status) === 'form'")
  const missing = card.slice(0, bounceAt)
  const bounceSlice = card.slice(bounceAt, readAt)
  const readSlice = card.slice(readAt, formAt)
  const formSlice = card.slice(formAt)
  expect(missing).toMatch(/NOT_REQUESTED/)
  expect(missing).not.toMatch(/customerName/)
  expect(missing).not.toMatch(/PriorMemory/)
  expect(bounceSlice.indexOf('customerName')).toBeLessThan(bounceSlice.indexOf('booking.preferredStartsAtLabel'))
  expect(bounceSlice).toMatch(/NOT_REQUESTED/)
  expect(bounceSlice).not.toMatch(/PriorMemory/)
  expect(bounceSlice).not.toMatch(/<form/)
  expect(bounceSlice).not.toMatch(/t\('owner\.propose'\)/)
  expect(bounceSlice).not.toMatch(/t\('owner\.accept'\)/)
  expect(bounceSlice).not.toMatch(/t\('owner\.decline'\)/)
  expect(readSlice.indexOf('customerName')).toBeLessThan(readSlice.indexOf('occupyingClockRange'))
  expect(readSlice).toMatch(/PriorMemory/)
  expect(readSlice).not.toMatch(/t\('owner\.propose'\)/)
  expect(formSlice.indexOf('customerName')).toBeLessThan(formSlice.indexOf('booking.preferredStartsAtLabel'))
  expect(formSlice).toMatch(/PriorMemory/)
  expect(formSlice).toMatch(/onPropose/)
  expect(formSlice).toMatch(/t\('owner\.propose'\)/)
  expect(formSlice).toMatch(/onAccept/)
  expect(formSlice).toMatch(/t\('owner\.accept'\)/)
  expect(formSlice).toMatch(/onDecline/)
  expect(formSlice).toMatch(/t\('owner\.decline'\)/)

  const pending = read('graphql/pending.ts')
  expect(pending).toMatch(/query OwnerBooking[\s\S]*priorConfirmedBookings/)
  expect(pending).toMatch(/noShowAt/)
  const i18n = read('i18n.ts')
  expect(i18n).toMatch(/back: 'Nazad'/)
  expect(i18n).toMatch(/NOT_REQUESTED: 'Zahtjev više nije na čekanju\.'/)
  expect(i18n).toMatch(/priorBookings: 'Raniji termini'/)
  expect(i18n).toMatch(/priorEmpty: 'Nema ranijih termina\.'/)
  expect(i18n).toMatch(/noShow: 'Nije došao'/)
  expect(read('App.tsx')).toMatch(/path="\/owner\/requests\/:id"/)
})
